/**
 * ORANGE SHIELD - ENGINE 04 · SPOOF DETECTOR
 *
 * Anti-spoofing identification for caller ID manipulation (per user request).
 * Detects the main spoofing classes seen in Brazil:
 *
 *   1. NEIGHBOR SPOOFING — calls that mimic the user's own number
 *      (same DDD + first digits), the classic "chamada de você mesmo".
 *   2. INVALID_DDD — caller ID uses a DDD that does not exist in the
 *      Brazilian numbering plan (impossible local number).
 *   3. BAD_LENGTH — mobile number without the 9th digit (pre-2012 format)
 *      or landline with 9 digits — physically impossible numbers.
 *   4. REPEATED_DIGITS / SEQUENTIAL_DIGITS — synthetic patterns typical of
 *      spoofed caller IDs generated by software.
 *   5. RAPID_REDIAL (Wangiri) — repeated short-interval calls, the
 *      "one ring and hang up" premium-rate scam pattern.
 *
 * Output: per-check pass/flag list + spoof score 0-100, consumed by
 * the Call Guard (as evidences), the Lookup API and the dedicated
 * Anti-Spoofing panel.
 */

import { db } from "@/lib/db";
import { clampScore } from "./types";

export const SPOOF_WEIGHTS = {
  NEIGHBOR_SPOOF: 35,
  INVALID_DDD: 30,
  BAD_LENGTH: 25,
  REPEATED_DIGITS: 25,
  SEQUENTIAL_DIGITS: 20,
  RAPID_REDIAL: 40,
} as const;

/** DDDs assigned by ANATEL (Brazilian numbering plan). */
export const VALID_DDDS = new Set([
  11, 12, 13, 14, 15, 16, 17, 19, 21, 22, 24, 27, 28, 31, 32, 33, 34, 35, 37,
  38, 41, 42, 43, 44, 45, 46, 47, 48, 49, 51, 53, 54, 55, 61, 62, 63, 64, 65,
  66, 67, 68, 69, 71, 73, 74, 75, 77, 79, 81, 82, 83, 84, 85, 86, 87, 88, 89,
  91, 92, 93, 94, 95, 96, 97, 98, 99,
]);

export interface SpoofCheck {
  code: string;
  label: string;
  detail: string;
  points: number;
  status: "pass" | "flagged" | "info";
}

export interface SpoofAnalysis {
  checks: SpoofCheck[];
  spoofScore: number;
  verdict: "clean" | "suspicious" | "spoof_likely";
  verdictLabel: string;
}

export function spoofVerdict(score: number): {
  verdict: SpoofAnalysis["verdict"];
  verdictLabel: string;
} {
  if (score >= 55) {
    return { verdict: "spoof_likely", verdictLabel: "Spoofing provável" };
  }
  if (score >= 25) {
    return { verdict: "suspicious", verdictLabel: "Indícios de spoofing" };
  }
  return { verdict: "clean", verdictLabel: "Nenhum indício de spoofing" };
}

/**
 * Parses a +55 number into { ddd, local }.
 * Returns null for shortcodes/international/alphanumeric senders.
 */
export function parseBrazilNumber(e164: string): { ddd: string; local: string } | null {
  const m = e164.match(/^\+55(\d{2})(\d{8,9})$/);
  if (!m) return null;
  return { ddd: m[1], local: m[2] };
}

/** Longest run of the same digit (e.g. "97777777" -> 7). */
function maxRepeatedRun(local: string): number {
  let best = 1;
  let cur = 1;
  for (let i = 1; i < local.length; i++) {
    cur = local[i] === local[i - 1] ? cur + 1 : 1;
    if (cur > best) best = cur;
  }
  return best;
}

/** Longest ascending or descending sequential digit run (e.g. "1234567" -> 7). */
function maxSequentialRun(local: string): number {
  let best = 1;
  let up = 1;
  let down = 1;
  for (let i = 1; i < local.length; i++) {
    const diff = local.charCodeAt(i) - local.charCodeAt(i - 1);
    up = diff === 1 ? up + 1 : 1;
    down = diff === -1 ? down + 1 : 1;
    best = Math.max(best, up, down);
  }
  return best;
}

/** Longest common suffix length between two digit strings. */
function commonSuffixLength(a: string, b: string): number {
  let i = 0;
  while (i < a.length && i < b.length && a[a.length - 1 - i] === b[b.length - 1 - i]) i++;
  return i;
}

/** Longest common prefix length between two digit strings. */
function commonPrefixLength(a: string, b: string): number {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i++;
  return i;
}

/**
 * Pure (non-DB) spoof checks over the caller ID format.
 * Used by the Call Guard, the Lookup API and the Anti-Spoofing panel.
 */
export function localSpoofChecks(e164: string, ownNumber: string): SpoofCheck[] {
  const checks: SpoofCheck[] = [];
  const br = parseBrazilNumber(e164);

  if (!br) {
    checks.push({
      code: "NOT_BRL",
      label: "Formato não-local",
      detail:
        e164.startsWith("+55")
          ? "Número curto/comercial ou formato atípico — checagens de DDD não aplicáveis"
          : "Número internacional — formatação brasileira não aplicável",
      points: 0,
      status: "info",
    });
    return checks;
  }

  const { ddd, local } = br;
  const dddNum = Number(ddd);
  const isMobileFormat = local.startsWith("9");
  const expectedLen = isMobileFormat ? 9 : 8;

  // 1. DDD validity
  if (!VALID_DDDS.has(dddNum)) {
    checks.push({
      code: "INVALID_DDD",
      label: "DDD inexistente no Brasil",
      detail: `O DDD ${ddd} não existe no plano de numeração da ANATEL — caller ID sintético`,
      points: SPOOF_WEIGHTS.INVALID_DDD,
      status: "flagged",
    });
  } else {
    checks.push({
      code: "VALID_DDD",
      label: `DDD ${ddd} válido`,
      detail: "Área de registro existente no plano da ANATEL",
      points: 0,
      status: "pass",
    });
  }

  // 2. Length consistency (9th digit rule)
  if (local.length !== expectedLen) {
    const detail = isMobileFormat
      ? `Celular com ${local.length} dígitos — deveria ter 9 (nono dígito ausente, formato pré-2012)`
      : `Fixo com ${local.length} dígitos — deveria ter 8`;
    checks.push({
      code: "BAD_LENGTH",
      label: "Comprimento inválido",
      detail,
      points: SPOOF_WEIGHTS.BAD_LENGTH,
      status: "flagged",
    });
  } else {
    checks.push({
      code: "OK_LENGTH",
      label: "Comprimento válido",
      detail: `${local.length} dígitos coerentes com ${isMobileFormat ? "celular" : "fixo"}`,
      points: 0,
      status: "pass",
    });
  }

  // 3. Repeated digits (synthetic patterns)
  const repeated = maxRepeatedRun(local);
  if (repeated >= 6) {
    checks.push({
      code: "REPEATED_DIGITS",
      label: "Dígitos repetidos em massa",
      detail: `Sequência de ${repeated} dígitos idênticos ("...${local.slice(0, repeated)}...") — padrão gerado por software`,
      points: SPOOF_WEIGHTS.REPEATED_DIGITS,
      status: "flagged",
    });
  } else {
    checks.push({
      code: "OK_DIGITS",
      label: "Padrão de dígitos normal",
      detail: "Sem repetições anormais",
      points: 0,
      status: "pass",
    });
  }

  // 4. Sequential digits (8+ consecutive digits are virtually impossible in real numbers)
  const sequential = maxSequentialRun(local);
  if (sequential >= 8) {
    checks.push({
      code: "SEQUENTIAL_DIGITS",
      label: "Sequência numérica artificial",
      detail: `Sequência de ${sequential} dígitos consecutivos — caller ID sintético`,
      points: SPOOF_WEIGHTS.SEQUENTIAL_DIGITS,
      status: "flagged",
    });
  } else {
    checks.push({
      code: "OK_SEQ",
      label: "Sem sequências artificiais",
      detail: "Distribuição de dígitos natural",
      points: 0,
      status: "pass",
    });
  }

  // 5. Neighbor spoofing (mimics the user's own number)
  const ownDigits = (ownNumber ?? "").replace(/\D/g, "");
  const ownLocal =
    ownDigits.startsWith("55") && ownDigits.length >= 12
      ? ownDigits.slice(4) // 55 + DDD(2) + local
      : ownDigits.length >= 8
        ? ownDigits.slice(-9)
        : "";

  if (ownLocal && ownLocal !== local) {
    const sameDdd = ownDigits.startsWith("55") && ownDigits.slice(2, 4) === ddd;
    const prefix = commonPrefixLength(ownLocal, local);
    const suffix = commonSuffixLength(ownLocal, local);
    const neighbor = (sameDdd && prefix >= 5) || suffix >= 7;

    if (neighbor) {
      const how = suffix >= 7 ? `termina com os mesmos ${suffix} dígitos do seu número` : `mesmo DDD + ${prefix} dígitos iniciais do seu número`;
      checks.push({
        code: "NEIGHBOR_SPOOF",
        label: "Neighbor spoofing (imita seu número)",
        detail: `Caller ID ${how} — técnica comum para passar pela desconfiança inicial`,
        points: SPOOF_WEIGHTS.NEIGHBOR_SPOOF,
        status: "flagged",
      });
    } else {
      checks.push({
        code: "OK_NEIGHBOR",
        label: "Não imita seu número",
        detail: "Sem semelhança relevante com o seu número",
        points: 0,
        status: "pass",
      });
    }
  } else {
    checks.push({
      code: "OWN_UNSET",
      label: "Neighbor spoofing não avaliado",
      detail: "Configure o seu número na aba Anti-Spoofing para ativar esta checagem",
      points: 0,
      status: "info",
    });
  }

  return checks;
}

/**
 * DB-backed check: rapid redial / Wangiri pattern.
 * >= 3 screening events for the same number in the last 15 minutes.
 */
export async function rapidRedialCheck(e164: string): Promise<SpoofCheck> {
  const since = new Date(Date.now() - 15 * 60 * 1000);
  const recent = await db.callEvent.count({
    where: { e164, occurredAt: { gte: since } },
  });

  if (recent >= 3) {
    return {
      code: "RAPID_REDIAL",
      label: "Rediscagem rápida (padrão Wangiri)",
      detail: `${recent} triagens nos últimos 15 minutos — esquema "1 toque e desliga" de tarifa premium`,
      points: SPOOF_WEIGHTS.RAPID_REDIAL,
      status: "flagged",
    };
  }
  return {
    code: "OK_REDIAL",
    label: "Sem rediscagem anormal",
    detail: `${recent} triagem(ns) nos últimos 15 minutos`,
    points: 0,
    status: "pass",
  };
}

/**
 * Full spoofing analysis (local checks + DB heuristics).
 * Read-only: does not record anything.
 */
export async function analyzeSpoofing(
  e164: string,
  ownNumber: string
): Promise<SpoofAnalysis> {
  const checks = localSpoofChecks(e164, ownNumber);
  // Wangiri check only makes sense for real phone numbers
  if (parseBrazilNumber(e164) || (!e164.startsWith("+55") && e164.length > 8)) {
    checks.push(await rapidRedialCheck(e164));
  }

  const spoofScore = clampScore(
    checks.reduce((sum, c) => sum + (c.status === "flagged" ? c.points : 0), 0)
  );
  const { verdict, verdictLabel } = spoofVerdict(spoofScore);

  return { checks, spoofScore, verdict, verdictLabel };
}
